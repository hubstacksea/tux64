#!/bin/bash
# Builds release packages into dist/:
#   tux64-VERSION-windows-x64.7z   (tux64.exe + README, unpack anywhere and run)
#   tux64_VERSION_amd64.deb        (Debian / Ubuntu)
#   tux64-VERSION-1.x86_64.rpm     (Fedora / RHEL / openSUSE)
# Usage: tools/package.sh [VERSION]    (needs 7z, dpkg-deb, rpmbuild, x86_64-w64-mingw32-gcc)
set -e
umask 022
cd "$(dirname "$0")/.."
VERSION="${1:-${VERSION:-1.0.0}}"
DIST=dist
WORK="$DIST/work"
PKG=tools/packaging

for t in 7z dpkg-deb rpmbuild x86_64-w64-mingw32-strip; do
    command -v $t >/dev/null || { echo "missing tool: $t"; exit 1; }
done

make -s all-platforms
rm -rf "$WORK"
mkdir -p "$WORK"

# ---------------- Windows: plain 7-Zip archive
WIN="$WORK/win/tux64-$VERSION"
mkdir -p "$WIN"
x86_64-w64-mingw32-strip -o "$WIN/tux64.exe" tux64.exe
cp README.md "$WIN/"
rm -f "$DIST/tux64-$VERSION-windows-x64.7z"
(cd "$WORK/win" && 7z a -t7z -mx=9 -bso0 -bsp0 "../../tux64-$VERSION-windows-x64.7z" "tux64-$VERSION")

# ---------------- Linux file tree shared by .deb and .rpm
ROOT="$WORK/root"
install -D -m 755 -s tux64 "$ROOT/usr/bin/tux64"
install -D -m 644 $PKG/tux64.desktop "$ROOT/usr/share/applications/tux64.desktop"
install -D -m 644 $PKG/tux64.png "$ROOT/usr/share/icons/hicolor/256x256/apps/tux64.png"
install -D -m 644 README.md "$ROOT/usr/share/doc/tux64/README.md"

# ---------------- .deb  (Debian policy: games live in /usr/games, docs need copyright + changelog)
DEB="$WORK/deb"
cp -a "$ROOT" "$DEB"
mkdir -p "$DEB/usr/games" "$DEB/DEBIAN"
mv "$DEB/usr/bin/tux64" "$DEB/usr/games/tux64"
rmdir "$DEB/usr/bin"
install -m 644 $PKG/copyright "$DEB/usr/share/doc/tux64/copyright"
printf 'tux64 (%s) unstable; urgency=low\n\n  * Release %s.\n\n -- tux64 <343302215+hubstacksea@users.noreply.github.com>  %s\n' \
    "$VERSION" "$VERSION" "$(date -R)" | gzip -9n > "$DEB/usr/share/doc/tux64/changelog.gz"
chmod 644 "$DEB/usr/share/doc/tux64/changelog.gz"
cat > "$DEB/DEBIAN/control" <<EOF
Package: tux64
Version: $VERSION
Section: games
Priority: optional
Architecture: amd64
Depends: libc6 (>= 2.34), libgl1, libx11-6
Recommends: libasound2t64 | libasound2
Installed-Size: $(du -sk "$ROOT" | cut -f1)
Maintainer: tux64 <343302215+hubstacksea@users.noreply.github.com>
Description: TUX 64 - The Kernel Castle Adventure
 A fan-made 3D action platformer starring Tux. Collect stars across snowy
 and icy worlds reached through the Kernel Castle, fight bosses and race.
 All graphics, music and sound effects are generated by the program itself.
EOF
dpkg-deb --root-owner-group -Zxz --build "$DEB" "$DIST/tux64_${VERSION}_amd64.deb" >/dev/null

# ---------------- .rpm
RPMTOP="$(pwd)/$WORK/rpm"
mkdir -p "$RPMTOP"
rpmbuild -bb --quiet \
    --define "_topdir $RPMTOP" \
    --define "tux_version $VERSION" \
    --define "tux_root $(pwd)/$ROOT" \
    --define "_build_id_links none" \
    $PKG/tux64.spec
cp "$RPMTOP"/RPMS/x86_64/tux64-"$VERSION"-1.x86_64.rpm "$DIST/"

rm -rf "$WORK"
ls -l "$DIST"
