#!/usr/bin/env python3
"""Generate src/lang_ja.c (translation table) and src/font_ja.h (bitmap glyphs of every
Japanese character used) from tools/translations_ja.py.

Needs Python 3 + Pillow and the Noto Sans CJK JP font (SIL Open Font License).
The generated files are committed, so building the game does not need any of this.

    python3 tools/gen_lang.py [path/to/NotoSansCJK-Bold.ttc]
"""
import os, sys, subprocess, json
from PIL import Image, ImageDraw, ImageFont

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
sys.path.insert(0, HERE)
from translations_ja import JA  # noqa: E402

CELL = 24
FONT = sys.argv[1] if len(sys.argv) > 1 else '/usr/share/fonts/opentype/noto/NotoSansCJK-Bold.ttc'
EXTRA = '「」『』、。・…ー～！？：（）★☆←→↑↓　'

def c_escape(s):
    out = []
    for ch in s:
        if ch == '\\': out.append('\\\\')
        elif ch == '"': out.append('\\"')
        elif ch == '\n': out.append('\\n')
        else: out.append(ch)
    return '"' + ''.join(out) + '"'

# --- check the keys exist in the sources
srcs = [os.path.join(ROOT, 'src', f) for f in ('game.c', 'levels.c', 'objects.c', 'player.c', 'sky.c', 'space.c', 'scale.c', 'vertical.c')]
found = set(json.loads(subprocess.check_output([sys.executable, os.path.join(HERE, 'extract_strings.py')] + srcs)))
missing = [k for k in JA if k not in found and k != 'LANGUAGE']
for k in missing:
    print('warning: translation key not found in sources: %r' % k[:60], file=sys.stderr)

# --- translation table
with open(os.path.join(ROOT, 'src', 'lang_ja.c'), 'w', encoding='utf-8') as f:
    f.write('/* lang_ja.c - GENERATED by tools/gen_lang.py from tools/translations_ja.py. Do not edit. */\n')
    f.write('#include "lang.h"\n\nconst char *const lang_ja_table[][2] = {\n')
    for k, v in JA.items():
        f.write('    { %s,\n      %s },\n' % (c_escape(k), c_escape(v)))
    f.write('};\nconst int lang_ja_count = (int)(sizeof lang_ja_table / sizeof lang_ja_table[0]);\n')

# --- glyphs
chars = set(EXTRA)
for v in JA.values():
    chars.update(ch for ch in v if ord(ch) >= 128)
codes = sorted(ord(c) for c in chars)
font = ImageFont.truetype(FONT, CELL - 2, index=0)
with open(os.path.join(ROOT, 'src', 'font_ja.h'), 'w', encoding='ascii') as f:
    f.write('/* font_ja.h - GENERATED by tools/gen_lang.py. Glyphs rendered from Noto Sans CJK JP Bold\n'
            ' * (c) Google, SIL Open Font License 1.1.  %d glyphs, %dx%d, 4-bit alpha. */\n' % (len(codes), CELL, CELL))
    f.write('#define JF_CELL %d\n#define JF_COUNT %d\n' % (CELL, len(codes)))
    f.write('static const unsigned short jf_codes[JF_COUNT] = {\n')
    for i in range(0, len(codes), 16):
        f.write('    ' + ', '.join('0x%04X' % c for c in codes[i:i + 16]) + ',\n')
    f.write('};\nstatic const unsigned char jf_bits[JF_COUNT][%d] = {\n' % (CELL * CELL // 2))
    for c in codes:
        img = Image.new('L', (CELL, CELL), 0)
        d = ImageDraw.Draw(img)
        ch = chr(c)
        bb = d.textbbox((0, 0), ch, font=font)
        w = bb[2] - bb[0]
        x = (CELL - w) // 2 - bb[0]
        y = (CELL - (CELL - 2)) // 2 - 3     # keep a common baseline for all glyphs
        if ch in '、。，．': x, y = 1 - bb[0], y      # punctuation sits at the left
        d.text((x, y), ch, fill=255, font=font)
        px = list(img.tobytes())
        packed = []
        for i in range(0, len(px), 2):
            packed.append((px[i] >> 4) | ((px[i + 1] >> 4) << 4))
        f.write('    {' + ','.join(str(b) for b in packed) + '},\n')
    f.write('};\n')
print('%d strings, %d glyphs' % (len(JA), len(codes)))
